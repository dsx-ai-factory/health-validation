// genverdictdocs writes an API reference from the generated verdict descriptor.
package main

import (
	"bytes"
	"fmt"
	"os"

	"google.golang.org/protobuf/reflect/protoreflect"

	healthv1 "github.com/dsx-ai-factory/health-validation/proto/go/health/v1"
)

func main() {
	if len(os.Args) != 2 {
		fmt.Fprintln(os.Stderr, "usage: genverdictdocs <output.md>")
		os.Exit(2)
	}
	if err := os.WriteFile(os.Args[1], reference(), 0o644); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func reference() []byte {
	file := healthv1.File_health_v1_verdict_proto
	var out bytes.Buffer
	fmt.Fprintln(&out, "{/* Code generated by proto/cmd/genverdictdocs. DO NOT EDIT. */}")
	fmt.Fprintln(&out, "\n# Verdict API reference")
	fmt.Fprintf(&out, "\nExperimental protobuf package `%s`. See [agent mode](/health-validation/operating/agent-mode) for HTTP examples, defaults, errors, and operational behavior. See [contract compatibility](https://github.com/dsx-ai-factory/health-validation/blob/main/proto/README.md) for schema versions and conversion limits.\n", file.Package())
	fmt.Fprintln(&out, "\nHTTP: `GET /verdict` accepts optional request fields as query parameters; `POST /verdict` accepts the request as JSON. Responses use snake_case proto field names and the catalog verdict JSON contract.")
	fmt.Fprintln(&out, "\n## Services")
	services := file.Services()
	for i := 0; i < services.Len(); i++ {
		service := services.Get(i)
		fmt.Fprintf(&out, "\n### %s\n\n| Method | Request | Response |\n| --- | --- | --- |\n", service.FullName())
		methods := service.Methods()
		for j := 0; j < methods.Len(); j++ {
			method := methods.Get(j)
			fmt.Fprintf(&out, "| `%s` | `%s` | `%s` |\n", method.Name(), method.Input().Name(), method.Output().Name())
		}
	}
	fmt.Fprintln(&out, "\n## Messages")
	messages := file.Messages()
	for i := 0; i < messages.Len(); i++ {
		message := messages.Get(i)
		fmt.Fprintf(&out, "\n### %s\n\n| Number | Field | Type | Presence |\n| --- | --- | --- | --- |\n", message.Name())
		fields := message.Fields()
		for j := 0; j < fields.Len(); j++ {
			field := fields.Get(j)
			presence := "implicit"
			if field.HasPresence() {
				presence = "explicit"
			}
			if field.IsList() || field.IsMap() {
				presence = "collection"
			}
			fmt.Fprintf(&out, "| %d | `%s` | `%s` | %s |\n", field.Number(), field.Name(), fieldType(field), presence)
		}
	}
	fmt.Fprintln(&out, "\n## Enums")
	enums := file.Enums()
	for i := 0; i < enums.Len(); i++ {
		enum := enums.Get(i)
		fmt.Fprintf(&out, "\n### %s\n\n| Number | JSON name |\n| --- | --- |\n", enum.Name())
		values := enum.Values()
		for j := 0; j < values.Len(); j++ {
			value := values.Get(j)
			fmt.Fprintf(&out, "| %d | `%s` |\n", value.Number(), value.Name())
		}
	}
	return out.Bytes()
}

func fieldType(field protoreflect.FieldDescriptor) string {
	if field.IsMap() {
		return fmt.Sprintf("map<%s, %s>", scalarType(field.MapKey()), scalarType(field.MapValue()))
	}
	if field.IsList() {
		return "repeated " + scalarType(field)
	}
	return scalarType(field)
}

func scalarType(field protoreflect.FieldDescriptor) string {
	if field.Kind() == protoreflect.MessageKind {
		return string(field.Message().FullName())
	}
	if field.Kind() == protoreflect.EnumKind {
		return string(field.Enum().Name())
	}
	return field.Kind().String()
}
