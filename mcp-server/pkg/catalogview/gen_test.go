const (
	generatedPath = "enums_gen.go"
	hvModule      = "github.com/dsx-ai-factory/health-validation"
)

var update = flag.Bool("update", false, "rewrite enums_gen.go from the compiled-in catalog (make docs)")

// The tool schemas offer only the values in enums_gen.go, so it must list exactly what
// the compiled-in catalog and catalog/health define. A bump of the hv module that adds a
// check, an architecture or an action fails here until `make docs` runs.
func TestGeneratedEnumsMatchTheCatalog(t *testing.T) {
	want := render(CheckIDs(), LiveArchitectures(), LiveCategories(), sourceActions(t))

	if *update {
		require.NoError(t, os.WriteFile(generatedPath, []byte(want), 0o600))
	}

	got, err := os.ReadFile(generatedPath)
	require.NoError(t, err)
	assert.Equal(t, want, string(got), "enums_gen.go is stale: run make docs")
}

func TestEveryActionHasAMeaning(t *testing.T) {
	for _, action := range RemediationActions {
		assert.NotEmpty(t, actionMeanings[action], "action %s has no meaning", action)
	}

	assert.Len(t, actionMeanings, len(RemediationActions), "a meaning names an action catalog/health lacks")
}

// sourceActions reads the RemediationAction constants from catalog/health/action.go in
// the hv module, since Go cannot list a package's constants at run time.
func sourceActions(t *testing.T) []string {
	t.Helper()

	out, err := exec.CommandContext(t.Context(), "go", "list", "-m", "-f", "{{.Dir}}", hvModule).Output()
	require.NoError(t, err, "finding the hv module")

	file, err := parser.ParseFile(token.NewFileSet(),
		filepath.Join(strings.TrimSpace(string(out)), "catalog", "health", "action.go"), nil, 0)
	require.NoError(t, err)

	var actions []string

	for _, declaration := range file.Decls {
		general, ok := declaration.(*ast.GenDecl)
		if !ok || general.Tok != token.CONST {
			continue
		}

		for _, spec := range general.Specs {
			value, ok := spec.(*ast.ValueSpec)
			if !ok || len(value.Values) != 1 {
				continue
			}

			if ident, ok := value.Type.(*ast.Ident); !ok || ident.Name != "RemediationAction" {
				continue
			}

			literal, ok := value.Values[0].(*ast.BasicLit)
			require.True(t, ok, "a RemediationAction constant that is not a literal")

			text, err := strconv.Unquote(literal.Value)
			require.NoError(t, err)

			actions = append(actions, text)
		}
	}

	require.NotEmpty(t, actions)
	slices.Sort(actions)

	return actions
}

func render(ids, architectures, categories, actions []string) string {
	var out strings.Builder

	out.WriteString("// SPDX-FileCopyrightText: Copyright (c) 2026, NVIDIA CORPORATION & AFFILIATES. All rights reserved.\n// SPDX-License-Identifier: Apache-2.0\n\n// Code generated by `make docs` from the health-validation catalog. DO NOT EDIT.\n\n")
	out.WriteString("package catalogview\n\n")
	writeList(&out, "CheckIDEnum lists every registered check ID.", "CheckIDEnum", ids)
	writeList(&out, "Architectures lists every architecture a registered check names.", "Architectures", architectures)
	writeList(&out, "Categories lists every category a registered check uses.", "Categories", categories)
	writeList(&out, "RemediationActions lists the RemediationAction constants in catalog/health.",
		"RemediationActions", actions)

	return strings.TrimSuffix(out.String(), "\n")
}

func writeList(out *strings.Builder, doc, name string, values []string) {
	fmt.Fprintf(out, "// %s\n//\n//nolint:gochecknoglobals // Generated data.\nvar %s = []string{\n", doc, name)

	for _, value := range values {
		fmt.Fprintf(out, "\t%q,\n", value)
	}

	out.WriteString("}\n\n")
}
