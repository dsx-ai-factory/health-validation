// gencheckpages reads checks.json and schema.json and writes the reference
// pages as plain Markdown: one page per check category under checks/, plus
// verdict-schema.md. Output is deterministic so a committed copy can be
// diffed against it.
package main

import (
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

const generatedNotice = "{/* Code generated by catalog/cmd/gencheckpages. DO NOT EDIT. */}\n\n"

type threshold struct {
	Value           any            `json:"value"`
	PerArchitecture map[string]any `json:"per_architecture"`
	Description     string         `json:"description"`
	Unit            string         `json:"unit"`
	Category        string         `json:"category"`
}

type action struct {
	OperationalState   string   `json:"operational_state"`
	RemediationActions []string `json:"remediation_actions"`
}

type rule struct {
	RecommendedAction *action `json:"recommended_action"`
	Expression        string  `json:"expression"`
	Message           string  `json:"message"`
	Severity          string  `json:"severity"`
}

type check struct {
	Thresholds        map[string]threshold `json:"thresholds"`
	RecommendedAction *action              `json:"recommended_action"`
	ID                string               `json:"id"`
	Name              string               `json:"name"`
	Description       string               `json:"description"`
	Category          string               `json:"category"`
	ConditionScope    string               `json:"condition_scope"`
	Provenance        string               `json:"provenance"`
	MaturityLevel     string               `json:"maturity_level"`
	ExecutionClass    string               `json:"execution_class"`
	Cadence           string               `json:"scheduling_cadence"`
	Rules             []rule               `json:"rules"`
	Contexts          []string             `json:"execution_contexts"`
	Architectures     []string             `json:"architectures"`
	Signals           []string             `json:"required_signals"`
}

type enumValue struct {
	Name        string `json:"name"`
	JSON        string `json:"json"`
	Description string `json:"description"`
}

type enumDef struct {
	Description string      `json:"description"`
	Values      []enumValue `json:"values"`
}

type field struct {
	Name        string `json:"name"`
	Type        string `json:"type"`
	JSON        string `json:"json"`
	Description string `json:"description"`
}

type structDef struct {
	Description string  `json:"description"`
	Fields      []field `json:"fields"`
}

type schema struct {
	Enums   map[string]enumDef   `json:"enums"`
	Structs map[string]structDef `json:"structs"`
}

func main() {
	if len(os.Args) != 4 {
		fmt.Fprintf(os.Stderr, "usage: gencheckpages <checks.json> <schema.json> <outdir>\n")
		os.Exit(1)
	}
	checksPath, schemaPath, outDir := os.Args[1], os.Args[2], os.Args[3]

	var checks []check
	readJSON(checksPath, &checks)
	var s schema
	readJSON(schemaPath, &s)

	byCategory := map[string][]check{}
	for _, c := range checks {
		byCategory[c.Category] = append(byCategory[c.Category], c)
	}

	checksDir := filepath.Join(outDir, "checks")
	if err := os.MkdirAll(checksDir, 0o755); err != nil {
		fatal(err)
	}

	// Categories follow the authored enum order; empty ones get no page.
	var listed []enumValue
	for _, cat := range s.Enums["Category"].Values {
		if len(byCategory[cat.JSON]) == 0 {
			continue
		}
		listed = append(listed, cat)
		writeFile(filepath.Join(checksDir, cat.JSON+".md"), categoryPage(cat, byCategory[cat.JSON]))
		delete(byCategory, cat.JSON)
	}
	if len(byCategory) > 0 {
		fatal(fmt.Errorf("checks use categories missing from the Category enum: %v", keys(byCategory)))
	}

	writeFile(filepath.Join(checksDir, "overview.md"), overviewPage(listed, checks))
	writeFile(filepath.Join(outDir, "verdict-schema.md"), schemaPage(s))
}

func overviewPage(cats []enumValue, checks []check) string {
	counts := map[string]int{}
	for _, c := range checks {
		counts[c.Category]++
	}
	var b strings.Builder
	b.WriteString(generatedNotice)
	b.WriteString("# Check Catalog\n\n")
	b.WriteString("Every check this build registers, grouped by hardware domain. Each page lists a check's ID, the signals it reads, its thresholds, and the rules that decide its severity.\n\n")
	b.WriteString("| Domain | Checks | Covers |\n|---|---|---|\n")
	for _, cat := range cats {
		fmt.Fprintf(&b, "| [%s](/health-validation/reference/checks/%s) | %d | %s |\n",
			cell(cat.Name), cat.JSON, counts[cat.JSON], cell(cat.Description))
	}
	return b.String()
}

// compactGroupMin is the smallest set of identical single-rule checks worth
// collapsing into one table.
const compactGroupMin = 5

func categoryPage(cat enumValue, checks []check) string {
	sort.Slice(checks, func(i, j int) bool { return naturalLess(checks[i].ID, checks[j].ID) })

	// Checks that share every property and carry one plain rule differ only in
	// ID, name, condition and action, so they read better as a table.
	groups := map[string][]check{}
	for _, c := range checks {
		if isCompact(c) {
			groups[propertySignature(c)] = append(groups[propertySignature(c)], c)
		}
	}

	var b strings.Builder
	b.WriteString(generatedNotice)
	fmt.Fprintf(&b, "# %s Checks\n\n%s\n\n", text(cat.Name), text(cat.Description))

	tabled := map[string]bool{}
	for _, c := range checks {
		sig := propertySignature(c)
		if !isCompact(c) || len(groups[sig]) < compactGroupMin || tabled[sig] {
			continue
		}
		tabled[sig] = true
		writeCompactGroup(&b, groups[sig])
	}
	for _, c := range checks {
		if isCompact(c) && len(groups[propertySignature(c)]) >= compactGroupMin {
			continue
		}
		writeCheck(&b, c)
	}
	return b.String()
}

// naturalLess orders IDs so embedded numbers compare by value:
// gpu_xid_46 sorts before gpu_xid_109.
func naturalLess(a, b string) bool {
	for a != "" && b != "" {
		an, ar := splitRun(a)
		bn, br := splitRun(b)
		if an != bn {
			if isDigit(an[0]) && isDigit(bn[0]) {
				an, bn = strings.TrimLeft(an, "0"), strings.TrimLeft(bn, "0")
				if len(an) != len(bn) {
					return len(an) < len(bn)
				}
			}
			return an < bn
		}
		a, b = ar, br
	}
	return len(a) < len(b)
}

// splitRun returns the leading run of digits or non-digits and the rest.
func splitRun(s string) (run, rest string) {
	digit := isDigit(s[0])
	i := 1
	for i < len(s) && isDigit(s[i]) == digit {
		i++
	}
	return s[:i], s[i:]
}

func isDigit(c byte) bool { return c >= '0' && c <= '9' }

func isCompact(c check) bool {
	return len(c.Rules) == 1 && c.Rules[0].RecommendedAction == nil
}

func propertySignature(c check) string {
	return strings.Join([]string{
		c.Provenance, c.ConditionScope, c.ExecutionClass, c.Cadence, c.MaturityLevel,
		strings.Join(c.Contexts, ","), strings.Join(c.Architectures, ","), strings.Join(c.Signals, ","),
		thresholdSignature(c.Thresholds),
	}, "\x00")
}

func thresholdSignature(thresholds map[string]threshold) string {
	var parts []string
	for _, name := range keys(thresholds) {
		t := thresholds[name]
		parts = append(parts, strings.Join([]string{
			name, thresholdValue(t), t.Unit, t.Category, t.Description,
		}, "\x00"))
	}
	return strings.Join(parts, "\x00")
}

func writeCompactGroup(b *strings.Builder, group []check) {
	first := group[0]
	fmt.Fprintf(b, "## Single-rule checks reading %s\n\n", codeList(first.Signals))
	fmt.Fprintf(b, "These %d checks share the properties below and each has one rule.\n\n", len(group))
	writeProperties(b, first)
	writeThresholds(b, first.Thresholds)
	b.WriteString("| Check | Name | Condition | Severity | Recommended action |\n|---|---|---|---|---|\n")
	for _, c := range group {
		r := c.Rules[0]
		fmt.Fprintf(b, "| %s | %s | %s | %s | %s |\n",
			tcode(c.ID), cell(c.Name), tcode(r.Expression), r.Severity, compactAction(c.RecommendedAction))
	}
	b.WriteString("\n")
}

func compactAction(a *action) string {
	if a == nil {
		return "none"
	}
	if len(a.RemediationActions) == 0 {
		return tcode(a.OperationalState)
	}
	steps := make([]string, len(a.RemediationActions))
	for i, s := range a.RemediationActions {
		steps[i] = tcode(s)
	}
	return tcode(a.OperationalState) + ": " + strings.Join(steps, " → ")
}

func writeCheck(b *strings.Builder, c check) {
	fmt.Fprintf(b, "## %s\n\n`%s`\n\n%s\n\n", text(c.Name), c.ID, text(c.Description))

	writeProperties(b, c)

	writeThresholds(b, c.Thresholds)

	if len(c.Rules) > 0 {
		b.WriteString("**Rules**\n\n")
		for _, r := range c.Rules {
			fmt.Fprintf(b, "- **%s** when %s\n  - Message: %s\n",
				r.Severity, code(r.Expression), text(r.Message))
			if r.RecommendedAction != nil {
				fmt.Fprintf(b, "  - Action: %s\n", actionText(r.RecommendedAction))
			}
		}
		b.WriteString("\n")
	}

	if c.RecommendedAction != nil {
		fmt.Fprintf(b, "**Recommended action:** %s\n\n", actionText(c.RecommendedAction))
	}
}

func writeThresholds(b *strings.Builder, thresholds map[string]threshold) {
	if len(thresholds) == 0 {
		return
	}
	b.WriteString("**Thresholds**\n\n| Name | Value | Unit | Category | Description |\n|---|---|---|---|---|\n")
	for _, name := range keys(thresholds) {
		t := thresholds[name]
		fmt.Fprintf(b, "| %s | %s | %s | %s | %s |\n",
			tcode(name), cell(thresholdValue(t)), cell(t.Unit), tcode(t.Category), cell(t.Description))
	}
	b.WriteString("\n")
}

func writeProperties(b *strings.Builder, c check) {
	b.WriteString("| Property | Value |\n|---|---|\n")
	row := func(k, v string) {
		if v != "" {
			fmt.Fprintf(b, "| %s | %s |\n", k, v)
		}
	}
	row("Provenance", tcode(c.Provenance))
	row("Condition scope", tcode(c.ConditionScope))
	row("Execution class", tcode(c.ExecutionClass))
	row("Scheduling cadence", tcode(c.Cadence))
	row("Maturity", tcode(c.MaturityLevel))
	row("Execution contexts", tcodeList(c.Contexts))
	row("Architectures", tcodeList(c.Architectures))
	row("Required signals", tcodeList(c.Signals))
	b.WriteString("\n")
}

func actionText(a *action) string {
	out := "operational state " + code(a.OperationalState)
	if len(a.RemediationActions) > 0 {
		steps := make([]string, len(a.RemediationActions))
		for i, s := range a.RemediationActions {
			steps[i] = code(s)
		}
		out += ", then " + strings.Join(steps, " → ")
	}
	return out
}

func thresholdValue(t threshold) string {
	if len(t.PerArchitecture) == 0 {
		return fmt.Sprint(t.Value)
	}
	var parts []string
	for _, arch := range keys(t.PerArchitecture) {
		parts = append(parts, fmt.Sprintf("%s: %v", arch, t.PerArchitecture[arch]))
	}
	// Architectures absent from the map fall back to Value.
	if t.Value != nil {
		parts = append(parts, fmt.Sprintf("other: %v", t.Value))
	}
	return strings.Join(parts, ", ")
}

func schemaPage(s schema) string {
	var b strings.Builder
	b.WriteString(generatedNotice)
	b.WriteString("# Verdict Schema\n\n")
	b.WriteString("Type definitions behind the verdict JSON. Enums serialize as strings, and struct fields are listed with their JSON key names. The machine-readable contract is [`node-verdict.schema.json`](https://github.com/dsx-ai-factory/health-validation/blob/main/catalog/health/node-verdict.schema.json).\n\n")

	b.WriteString("## Structs\n\n")
	for _, name := range keys(s.Structs) {
		def := s.Structs[name]
		fmt.Fprintf(&b, "### %s\n\n%s\n\n", name, text(def.Description))
		if len(def.Fields) == 0 {
			continue
		}
		b.WriteString("| Field | JSON name | Type | Description |\n|---|---|---|---|\n")
		for _, f := range def.Fields {
			fmt.Fprintf(&b, "| %s | %s | %s | %s |\n",
				tcode(f.Name), tcode(f.JSON), typeRef(f.Type, s), cell(f.Description))
		}
		b.WriteString("\n")
	}

	b.WriteString("## Enums\n\n")
	for _, name := range keys(s.Enums) {
		def := s.Enums[name]
		fmt.Fprintf(&b, "### %s\n\n%s\n\n", name, text(def.Description))
		b.WriteString("| Name | JSON value | Description |\n|---|---|---|\n")
		for _, v := range def.Values {
			fmt.Fprintf(&b, "| %s | %s | %s |\n", tcode(v.Name), tcode(v.JSON), cell(v.Description))
		}
		b.WriteString("\n")
	}
	return b.String()
}

// typeRef links a field's type to its definition when the base type is
// declared in the schema.
func typeRef(typ string, s schema) string {
	base := typ
	if i := strings.LastIndexAny(base, "]."); i >= 0 {
		base = base[i+1:]
	}
	_, isStruct := s.Structs[base]
	_, isEnum := s.Enums[base]
	if isStruct || isEnum {
		return fmt.Sprintf("[%s](#%s)", tcode(typ), strings.ToLower(base))
	}
	return tcode(typ)
}

// text escapes prose for MDX: braces start expressions and a bare < starts
// a tag.
func text(s string) string {
	s = strings.Join(strings.Fields(s), " ")
	s = strings.ReplaceAll(s, "{", "\\{")
	s = strings.ReplaceAll(s, "}", "\\}")
	s = strings.ReplaceAll(s, "<", "&lt;")
	return s
}

// cell is text for a table cell, where | would end the cell.
func cell(s string) string {
	return strings.ReplaceAll(text(s), "|", "\\|")
}

// code wraps s in an inline code span.
func code(s string) string {
	if s == "" {
		return ""
	}
	fence := "`"
	if strings.Contains(s, "`") {
		fence = "``"
	}
	return fence + strings.Join(strings.Fields(s), " ") + fence
}

// tcode is code for a table cell. The Fern theme lets code in table cells wrap
// at any character, which splits paths and IDs; <nobr> keeps each span whole.
func tcode(s string) string {
	c := strings.ReplaceAll(code(s), "|", "\\|")
	if c == "" {
		return ""
	}
	return "<nobr>" + c + "</nobr>"
}

func tcodeList(items []string) string {
	out := make([]string, len(items))
	for i, it := range items {
		out[i] = tcode(it)
	}
	return strings.Join(out, ", ")
}

func codeList(items []string) string {
	out := make([]string, len(items))
	for i, it := range items {
		out[i] = code(it)
	}
	return strings.Join(out, ", ")
}

func keys[V any](m map[string]V) []string {
	out := make([]string, 0, len(m))
	for k := range m {
		out = append(out, k)
	}
	sort.Strings(out)
	return out
}

func readJSON(path string, v any) {
	data, err := os.ReadFile(path)
	if err != nil {
		fatal(err)
	}
	if err := json.Unmarshal(data, v); err != nil {
		fatal(fmt.Errorf("%s: %w", path, err))
	}
}

func writeFile(path, content string) {
	if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
		fatal(err)
	}
}

func fatal(err error) {
	fmt.Fprintf(os.Stderr, "gencheckpages: %v\n", err)
	os.Exit(1)
}
